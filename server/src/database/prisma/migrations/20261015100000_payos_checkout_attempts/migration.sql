CREATE TABLE payment_attempts (
    id CHAR(36) NOT NULL,
    owner_scope VARCHAR(320) NOT NULL,
    idempotency_key_hash CHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    snapshot_hash CHAR(64) NOT NULL,
    pending_checkout_id INT NOT NULL,
    provider VARCHAR(32) NOT NULL,
    provider_order_code BIGINT UNSIGNED NOT NULL,
    provider_link_id VARCHAR(255) NULL,
    provider_link_url TEXT NULL,
    expected_amount_vnd BIGINT UNSIGNED NOT NULL,
    verified_received_amount_vnd BIGINT UNSIGNED NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    payment_state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    order_state VARCHAR(24) NOT NULL DEFAULT 'NOT_CREATED',
    resolution_state VARCHAR(24) NOT NULL DEFAULT 'NONE',
    order_id INT NULL,
    display_snapshot JSON NOT NULL,
    expires_at DATETIME(3) NOT NULL,
    create_lease_token CHAR(36) NULL,
    create_lease_until DATETIME(3) NULL,
    last_checked_at DATETIME(3) NULL,
    retry_after_seconds INT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_attempts_owner_idempotency (owner_scope, idempotency_key_hash),
    UNIQUE KEY uq_payment_attempts_provider_order_code (provider, provider_order_code),
    UNIQUE KEY uq_payment_attempts_provider_link (provider, provider_link_id),
    UNIQUE KEY uq_payment_attempts_pending_checkout (pending_checkout_id),
    UNIQUE KEY uq_payment_attempts_order (order_id),
    KEY idx_payment_attempts_payment_expiry (payment_state, expires_at),
    KEY idx_payment_attempts_order_resolution (order_state, resolution_state, updated_at),
    CONSTRAINT chk_payment_attempts_expected_vnd CHECK (expected_amount_vnd > 0 AND expected_amount_vnd <= 9007199254740991),
    CONSTRAINT chk_payment_attempts_received_vnd CHECK (verified_received_amount_vnd <= 9007199254740991),
    CONSTRAINT fk_payment_attempts_pending_checkout FOREIGN KEY (pending_checkout_id) REFERENCES pending_checkouts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_payment_attempts_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE payment_attempt_observations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    attempt_id CHAR(36) NOT NULL,
    source VARCHAR(16) NOT NULL,
    source_key VARCHAR(255) NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    provider_order_code BIGINT UNSIGNED NULL,
    provider_link_id VARCHAR(255) NULL,
    expected_amount_vnd BIGINT UNSIGNED NOT NULL,
    reported_amount_vnd BIGINT UNSIGNED NULL,
    paid_amount_vnd BIGINT UNSIGNED NULL,
    currency CHAR(3) NULL,
    normalized_status VARCHAR(32) NOT NULL,
    verified TINYINT(1) NOT NULL DEFAULT 0,
    verified_at DATETIME(3) NULL,
    sanitized_reason VARCHAR(500) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_attempt_observation_payload (attempt_id, source, source_key, payload_hash),
    KEY idx_payment_attempt_observations_source (attempt_id, source, source_key),
    KEY idx_payment_attempt_observations_created (attempt_id, created_at),
    CONSTRAINT fk_payment_attempt_observations_attempt FOREIGN KEY (attempt_id) REFERENCES payment_attempts (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE payment_attempt_refunds (
    id CHAR(36) NOT NULL,
    attempt_id CHAR(36) NOT NULL,
    transfer_reference VARCHAR(191) NOT NULL,
    idempotency_key VARCHAR(191) NOT NULL,
    amount_vnd BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    transferred_at DATE NOT NULL,
    evidence_id INT NOT NULL,
    actor_id VARCHAR(255) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_attempt_refunds_transfer_reference (transfer_reference),
    UNIQUE KEY uq_payment_attempt_refunds_idempotency (idempotency_key),
    KEY idx_payment_attempt_refunds_attempt_created (attempt_id, created_at),
    CONSTRAINT chk_payment_attempt_refunds_amount CHECK (amount_vnd > 0 AND amount_vnd <= 9007199254740991),
    CONSTRAINT fk_payment_attempt_refunds_attempt FOREIGN KEY (attempt_id) REFERENCES payment_attempts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_payment_attempt_refunds_evidence FOREIGN KEY (evidence_id) REFERENCES financial_evidence (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_payment_attempt_refunds_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
