const translateVietnameseAdminCopy = (source: string): string => {
    const exact = viAdminCopy[source] ?? viAdminCopyExtra[source];
    if (exact) return exact;

    const invalidAttributeKey = source.match(/^Attribute key must use lowercase snake_case: (.+)$/);
    if (invalidAttributeKey) return `Khóa thuộc tính phải dùng chữ thường và dấu gạch dưới: ${invalidAttributeKey[1]}`;

    const duplicateAttributeKey = source.match(/^Duplicate attribute key: (.+)$/);
    if (duplicateAttributeKey) return `Khóa thuộc tính bị trùng: ${duplicateAttributeKey[1]}`;

    const attributeValidation = source.match(/^Attribute (.+) (needs a label|needs a value|must contain a valid number)\.$/);
    if (attributeValidation) {
        const message = attributeValidation[2] === "needs a label"
            ? "cần có tên hiển thị"
            : attributeValidation[2] === "needs a value"
                ? "cần có giá trị"
                : "phải chứa một số hợp lệ";
        return `Thuộc tính ${attributeValidation[1]} ${message}.`;
    }

    return source;
};

export const translateAdminCopy = (locale: Locale, source: string): string =>
    locale === "vi" ? translateVietnameseAdminCopy(source) : source;
